# Builds engine/webster-voice.js from a Webster page: the formant engine, the phoneme tables and every
# language's text-to-phoneme rules, without its UI and without the experimental Physical (DWM) engine.
# usage: python3 tools/webster/extract.py path/to/webster-dwm-v3.html
import sys, os, re
src = open(sys.argv[1], encoding='utf-8').read()
js = src[src.index('<script>') + 8: src.rindex('</script>')]
a = js[:js.index('/**\n * AREA FUNCTION PRESETS')]                     # presets, phonemes, symbol + number expanders
b = js[js.index('function engInflectionPhonemes'): js.index('const app = {')]   # English dictionary, G2P, FormantSynth
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
# englishG2P's fallback dropped diphthongs/affricates ("eɪ", "tʃ") because they aren't table phonemes;
# keep them (voice-api.js splits them into their parts). Webster itself is left untouched.
FIX = "return ph.filter(p => PHONEMES[p] || p === '_');"
assert FIX in b, 'Webster changed: re-check the englishG2P filter'
b = b.replace(FIX, "return ph.filter(p => PHONEMES[p] || SPLIT[p] || p === '_');")
wrap = open(os.path.join(root, 'tools', 'webster', 'voice-api.js'), encoding='utf-8').read()
out = ('// ==== WEBSTER VOICE (formant speech, from Webster v3; generated by tools/webster/extract.py, edit Webster or voice-api.js) ====\n'
       '// MIT License, ConsciousNode SoftWorks. Webster is the studio\'s own formant synthesizer: Web Audio only, offline.\n'
       'const WebsterVoice = (() => {\n' + a + b + wrap + '\n})();\n// ==== END WEBSTER VOICE ====\n')
assert '</script' not in out.lower()
open(os.path.join(root, 'engine', 'webster-voice.js'), 'w', encoding='utf-8').write(out)
print(f'engine/webster-voice.js: {len(out) / 1e3:.0f} KB')
