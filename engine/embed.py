# Embeds engine/rwkv7-engine.js and engine/rwkv_world_vocab.json into the pip-suite pages, between
# <!-- RWKV7-ENGINE:BEGIN --> and <!-- RWKV7-ENGINE:END --> (inserted before the page's main <script> the
# first time). The pages stay single-file and dependency-free; this script is only for developers.
# usage: python3 engine/embed.py        (then: node tests/engine-ref.js)
import os, re, json
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
engine = open(os.path.join(root, 'engine', 'rwkv7-engine.js'), encoding='utf-8').read()
vocab = json.load(open(os.path.join(root, 'engine', 'rwkv_world_vocab.json'), encoding='utf-8'))
assert '</script' not in engine.lower()
vocab_json = json.dumps({'tokens': vocab['tokens']}, separators=(',', ':'))
block = ('<!-- RWKV7-ENGINE:BEGIN (generated by engine/embed.py from engine/rwkv7-engine.js; edit that file, not this block) -->\n'
         '<script type="application/json" id="rwkv-world-vocab">' + vocab_json + '</script>\n'
         '<script>\n' + engine + '</script>\n<!-- RWKV7-ENGINE:END -->\n')
for page in ('junto-orchestrator.html', 'multi-pip-chat.html'):
    p = os.path.join(root, 'pip-suite', page); s = open(p, encoding='utf-8').read()
    if '<!-- RWKV7-ENGINE:BEGIN' in s:
        s = re.sub(r'<!-- RWKV7-ENGINE:BEGIN.*?<!-- RWKV7-ENGINE:END -->\n', lambda m: block, s, count=1, flags=re.S)
    else:
        i = s.index('\n<script>\n/**') + 1; s = s[:i] + block + s[i:]
    open(p, 'w', encoding='utf-8').write(s); print(f'{page}: engine embedded ({len(s) / 1e6:.2f} MB)')
